// Real Logos2 GPLL clock source. VCO = 27 MHz * 2 * 21 = 1134 MHz.
// CLKOUT0 /28 = 40.5 MHz; /21 = 54 MHz; /42 = 27 MHz.
`default_nettype none
module nr_board_clock #(parameter integer CLK_HZ=40500000)(
 input wire clk_27m,reset,output wire clk_system,locked
);
 localparam integer OUT_DIV=(CLK_HZ==54000000)?21:(CLK_HZ==40500000)?28:42;
 GTP_GPLL #(.CLKIN_FREQ(27.0),.LOCK_MODE(0),.STATIC_RATIOI(1),
  .STATIC_RATIOM(2),.STATIC_RATIOF(21.0),.STATIC_RATIO0(OUT_DIV*1.0),
  .STATIC_DUTY0(OUT_DIV),.STATIC_RATIO1(23),.STATIC_RATIO2(23),
  .STATIC_RATIO3(23),.STATIC_RATIO4(23),.STATIC_RATIO5(23),.STATIC_RATIO6(23),
  .STATIC_DUTY1(23),.STATIC_DUTY2(23),.STATIC_DUTY3(23),.STATIC_DUTY4(23),
  .STATIC_DUTY5(23),.STATIC_DUTY6(23),.STATIC_DUTYF(21),.INTERNAL_FB("CLKOUTF"),
  .EXTERNAL_FB("DISABLE"),.SSC_MODE("DISABLE"),.BANDWIDTH("OPTIMIZED")) u_gpll (
  .CLKIN1(clk_27m),.CLKIN2(1'b0),.CLKIN_SEL(1'b0),.CLKFB(1'b0),
  .CLKOUT0(clk_system),.LOCK(locked),.DPS_CLK(1'b0),.DPS_EN(1'b0),.DPS_DIR(1'b0),
  .CLKOUT0_SYN(1'b0),.CLKOUT1_SYN(1'b0),.CLKOUT2_SYN(1'b0),
  .CLKOUT3_SYN(1'b0),.CLKOUT4_SYN(1'b0),.CLKOUT5_SYN(1'b0),
  .CLKOUT6_SYN(1'b0),.CLKOUTF_SYN(1'b0),.PLL_PWD(1'b0),.RST(reset),
  .APB_CLK(1'b0),.APB_RST_N(1'b0),.APB_ADDR(5'd0),.APB_SEL(1'b0),
  .APB_EN(1'b0),.APB_WRITE(1'b0),.APB_WDATA(16'd0)
 );
 initial if(CLK_HZ!=27000000 && CLK_HZ!=40500000 && CLK_HZ!=54000000)
  $fatal(1,"Unsupported GPLL clock target");
endmodule
`default_nettype wire
