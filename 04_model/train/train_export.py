def dataset(templates, path, augment=False):
    data = []
    rng = np.random.RandomState(123 if augment else 456)
    for intent, phrases in templates.items():
        for template_id, phrase in enumerate(phrases):
            chinese = any(ord(ch)>127 for ch in phrase)
            prefixes = ["","请","帮我","现在","麻烦","我想"] if chinese else ["","please ","can you ","i want to ","help me ","now "]
            suffixes = ["","一下","吧","，谢谢","现在","。"] if chinese else [""," please"," now"," on board"," for me","."]
            numeric = "{n}" in phrase
            count = 24 if augment else (8 if numeric else 1)
            for sample in range(count):
                value = int(rng.randint(0,256 if intent=="set_led" else 101)) if augment else [0,1,7,32,63,80,99,100][sample%8]
                prefix = prefixes[int(rng.randint(0,len(prefixes)))] if augment else ""
                suffix = suffixes[int(rng.randint(0,len(suffixes)))] if augment else ""
                text = prefix + phrase.format(n=value) + suffix
                if len(text.encode("utf-8")) > SEQ:
                    text = phrase.format(n=value)
                data.append(dict(text=text, intent=intent, arg=value if numeric else None,
                                 template_id=intent + ":" + str(template_id)))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in data), encoding="utf-8")
    tokens, lengths = zip(*(tokenize(x["text"]) for x in data))
    targets = [TOOLS.index(x["intent"]) for x in data]
    return data, torch.tensor(tokens), torch.tensor(lengths), torch.tensor(targets)

def quant_weight(weight):
    arr = weight.detach().cpu().numpy()
    maximum = max(float(abs(arr).max()), 1e-6)
    shift = max(-8, min(16, int(math.floor(math.log2(7.0 / maximum)))))
    # np.rint 和 PyTorch 一致；整数运行时使用对称四舍五入。
    q = np.clip(np.rint(arr * 2.0 ** shift), -8, 7).astype(np.int8)
    return q, shift

def pack(q):
    flat = q.reshape(-1)
    if len(flat) % 2:
        flat = np.append(flat, 0)
    return ((flat[0::2].astype(np.uint8) & 15) | ((flat[1::2].astype(np.uint8) & 15) << 4)).astype(np.uint8)

def export(model):
    destination = ROOT / "04_model/export"
    destination.mkdir(parents=True, exist_ok=True)
    arrays = {}
    spec = {"format":"nr-byte-tool-int4-v1", "model_kind":"2-layer attention intent encoder",
            "d_model": model.d, "seq_len":SEQ, "heads":4, "layers":2, "activation_scale":32,
            "vocabulary":"UTF-8 byte values 0..255", "tools":list(TOOLS), "tensors":[]}
    lines = ["/* Generated by 04_model/train/train_export.py. Do not hand-edit. */",
             "#ifndef NR_BYTE_MODEL_DATA_H", "#define NR_BYTE_MODEL_DATA_H",
             "#include <stdint.h>", "#define NR_D " + str(model.d), "#define NR_SEQ 64",
             "#define NR_HEADS 4", "#define NR_LAYERS 2", "#define NR_CLASSES 6"]
    for name, param in model.named_parameters():
        ident = "nr_" + name.replace(".", "_")
        if name.endswith(".weight"):
            q, shift = quant_weight(param)
            data = pack(q)
            arrays[name] = q
            arrays[name + ".shift"] = np.array(shift, dtype=np.int32)
            spec["tensors"].append({"name":name,"shape":list(q.shape),"shift":shift,"packed_bytes":int(data.size)})
            lines.append("#define " + ident.upper() + "_SHIFT " + str(shift))
            lines.append("static const uint8_t " + ident + "[] __attribute__((aligned(4))) = {")
            lines.extend("  " + ",".join(str(int(v)) for v in data[i:i+24]) + "," for i in range(0, len(data), 24))
        else:
            data = np.rint(param.detach().cpu().numpy() * 32).astype(np.int32)
            arrays[name] = data
            lines.append("static const int32_t " + ident + "[] __attribute__((aligned(4))) = {")
            lines.extend("  " + ",".join(str(int(v)) for v in data[i:i+16]) + "," for i in range(0, len(data),16))
        lines.append("};")
    exp_lut = np.maximum(1, np.rint(np.exp(-np.arange(129) / 16.0) * 4096)).astype(np.int32)
    arrays["exp_lut"] = exp_lut
    lines.append("static const uint16_t nr_exp_lut[129] = {" + ",".join(str(x) for x in exp_lut) + "};")
    lines.append("#endif")
    np.savez_compressed(destination / "current_int4.npz", **arrays)
    spec["packed_weight_bytes"] = sum(x["packed_bytes"] for x in spec["tensors"])
    spec["bias_bytes"] = sum(x.nbytes for n,x in arrays.items() if n.endswith(".bias"))
    spec["total_model_bytes"] = spec["packed_weight_bytes"] + spec["bias_bytes"] + exp_lut.size * 2
    # 5个sequence buffers + 1个FFN buffer + pooled/logit/score workspace。
    spec["runtime_scratch_upper_bytes"] = (5 * SEQ * model.d + SEQ * 2 * model.d) + 3 * SEQ * 4 + model.d + model.d * 4
    spec["onchip_profile"] = "BRAM64 bring-up" if model.d == 64 else "DDR128 target"
    (destination / "current_manifest.json").write_text(json.dumps(spec,ensure_ascii=False,indent=2)+"\n", encoding="utf-8")
    cdir = ROOT / "03_sw/model"
    cdir.mkdir(parents=True, exist_ok=True)
    (cdir / "byte_model_data.h").write_text("\n".join(lines)+"\n", encoding="utf-8")
    return spec

